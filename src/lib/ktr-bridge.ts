export type GarmentFamily = 'bodice' | 'skirt' | 'trousers' | 'jacket';

import type { StudioMeasurementValues } from './measurement-profile';

export type StudioMeasurements = StudioMeasurementValues;

export interface EaseProfile {
  bust: number;
  waist: number;
  hip: number;
  upperArm: number;
}

/**
 * Emit only the currently documented KTR v0.1 subset used by this studio:
 * input declarations, arithmetic, typed functions, and point constructors.
 * This intentionally does not emit piece/export/search/assert until the upstream
 * compiler/runtime reports those features as implemented.
 */
export function buildKtrSource(m: StudioMeasurements, e: EaseProfile): string {
  const mm = (cm: number) => Math.round(cm * 10);
  return `// Generated by Pattern Studio — KTR-compatible source draft
// Measurements are stored in cm in the UI and emitted as millimetres.

input bust = ${mm(m.bust)}mm
input waist = ${mm(m.waist)}mm
input hip = ${mm(m.hip)}mm
input back_length = ${mm(m.backLength)}mm
input sleeve_length = ${mm(m.sleeveLength)}mm
input upper_arm = ${mm(m.upperArm)}mm

// Local ease inputs are independent design variables.
input bust_ease = ${mm(e.bust)}mm
input waist_ease = ${mm(e.waist)}mm
input hip_ease = ${mm(e.hip)}mm
input upper_arm_ease = ${mm(e.upperArm)}mm

fn quarter_bust(ease: length) {
  let width = bust / 4 + ease
  return point(width, 0mm)
}

fn quarter_waist(ease: length) {
  let width = waist / 4 + ease
  return point(width, 0mm)
}

fn quarter_hip(ease: length) {
  let width = hip / 4 + ease
  return point(width, 0mm)
}

let bust_reference = quarter_bust(bust_ease)
let waist_reference = quarter_waist(waist_ease)
let hip_reference = quarter_hip(hip_ease)
`;
}
